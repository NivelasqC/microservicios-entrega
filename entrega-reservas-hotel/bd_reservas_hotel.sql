CREATE TABLE RESERVAS_HOTEL (
    ID                    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE_CLIENTE        VARCHAR2(100) NOT NULL,
    HOTEL                 VARCHAR2(100) NOT NULL,
    CIUDAD                VARCHAR2(80)  NOT NULL,
    FECHA_ENTRADA         DATE          NOT NULL,
    FECHA_SALIDA          DATE          NOT NULL,
    TIPO_HABITACION       VARCHAR2(50)  NOT NULL,
    CANTIDAD_HUESPEDES    NUMBER        NOT NULL,
    ESTADO_RESERVA        VARCHAR2(20)  NOT NULL,
    OBSERVACION           VARCHAR2(200),

    CONSTRAINT CHK_RESERVA_ESTADO
        CHECK (ESTADO_RESERVA IN ('CONFIRMADA', 'CANCELADA', 'PENDIENTE')),

    CONSTRAINT CHK_HUESPEDES
        CHECK (CANTIDAD_HUESPEDES > 0)
);
