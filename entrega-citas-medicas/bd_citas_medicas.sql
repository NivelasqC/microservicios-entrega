CREATE TABLE CITAS_MEDICAS (
    ID               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE_PACIENTE  VARCHAR2(100) NOT NULL,
    NOMBRE_MEDICO    VARCHAR2(100) NOT NULL,
    ESPECIALIDAD     VARCHAR2(80)  NOT NULL,
    FECHA_CITA       DATE          NOT NULL,
    HORA_CITA        VARCHAR2(5)   NOT NULL,
    ESTADO           VARCHAR2(20)  NOT NULL,
    OBSERVACION      VARCHAR2(200),

    CONSTRAINT CHK_CITAS_ESTADO
        CHECK (ESTADO IN ('PROGRAMADA', 'CANCELADA', 'DISPONIBLE', 'FINALIZADA')),

    CONSTRAINT CHK_CITAS_HORA
        CHECK (REGEXP_LIKE(HORA_CITA, '^(0[0-9]|1[0-9]|2[0-3]):[0-5][0-9]$'))
);
